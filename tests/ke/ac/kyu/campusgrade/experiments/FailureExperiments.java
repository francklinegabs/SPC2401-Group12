package ke.ac.kyu.campusgrade.experiments;

import ke.ac.kyu.campusgrade.integration.Proc;

import java.io.IOException;
import java.net.ServerSocket;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Section 7.3 experiments, each with real separate processes. Run with:
 * <pre>java -cp out/classes;out/test-classes ke.ac.kyu.campusgrade.experiments.FailureExperiments</pre>
 * Every process output and a summary.md go to evidence/experiments/.
 */
public final class FailureExperiments {

    private static final String SERVER = "ke.ac.kyu.campusgrade.server.GradeServer";
    private static final String STUDENT = "ke.ac.kyu.campusgrade.client.StudentClient";
    private static final String LECTURER = "ke.ac.kyu.campusgrade.client.LecturerClient";

    private static final Path ROOT = Path.of("evidence", "experiments");
    private static final StringBuilder SUMMARY = new StringBuilder();

    public static void main(String[] args) throws Exception {
        deleteTree(ROOT);
        Files.createDirectories(ROOT);
        SUMMARY.append("# 7.3 experiment summary\n\nGenerated by FailureExperiments on ")
                .append(java.time.OffsetDateTime.now()).append("\n");
        List<String> which = List.of(args);
        if (which.isEmpty() || which.contains("D")) concurrentProcesses();
        if (which.isEmpty() || which.contains("A1")) serverKilledBeforeApply();
        if (which.isEmpty() || which.contains("A2")) serverKilledAfterApply();
        if (which.isEmpty() || which.contains("B")) subscriberOffline();
        if (which.isEmpty() || which.contains("C")) networkDelay();
        Files.writeString(ROOT.resolve("summary.md"), SUMMARY.toString(), StandardCharsets.UTF_8);
        System.out.println(SUMMARY);
        System.exit(0);
    }

    // ------------------------------------------------------------------ D

    /** 22 lecturer processes submit at the same moment. */
    static void concurrentProcesses() throws Exception {
        Path dir = ROOT.resolve("D-22-concurrent-clients");
        int port = freePort();
        List<String> common = common(port, dir);
        int n = 22;
        try (Proc server = Proc.start("server", dir, plus(common, "-Dkyu.registry.create=true",
                "-Dkyu.server.journal=none"), SERVER)) {
            server.awaitOutput("server ready", 15_000);
            List<Proc> clients = new ArrayList<>();
            long t0 = System.nanoTime();
            for (int i = 1; i <= n; i++) {
                String sid = String.format("KYU%03d", i);
                clients.add(Proc.start("lecturer-" + i, dir, common, LECTURER,
                        "submit " + sid + " SPC2401 " + (50 + i) + "; submit KYU999 SPC2402 " + i));
            }
            boolean allDone = true;
            for (Proc c : clients) {
                allDone &= c.awaitExit(60_000);
            }
            long ms = (System.nanoTime() - t0) / 1_000_000;
            try (Proc check = Proc.start("lecturer-check", dir, common, LECTURER, "list SPC2401; list SPC2402")) {
                check.awaitExit(30_000);
                String out = check.output();
                int ok = 0;
                for (Proc c : clients) {
                    ok += count(c.output(), "OK stored");
                }
                long applied = count(server.output(), "applied req=");
                section("D. 22 lecturer processes submit at once",
                        "- processes finished: " + allDone + " in " + ms + " ms (includes 22 JVM start-ups)\n"
                                + "- client OK replies: " + ok + " / " + (2 * n) + "\n"
                                + "- server 'applied' log lines: " + applied + "\n"
                                + "- " + grep(out, "LIST SPC2401") + "\n"
                                + "- " + grep(out, "LIST SPC2402") + " (22 writers, one key: last writer wins)\n"
                                + "- server FAILURE lines: " + count(server.output(), "[FAILURE]") + "\n"
                                + "- Result: no lost update (44 applied = 44 sent), no deadlock (all exited).");
            }
        }
    }

    // ----------------------------------------------------------------- A1

    /** Server killed while the call is executing, BEFORE the mark is stored. */
    static void serverKilledBeforeApply() throws Exception {
        Path dir = ROOT.resolve("A1-server-killed-before-apply");
        int port = freePort();
        Path journal = dir.resolve("marks.journal");
        List<String> common = common(port, dir);
        List<String> srv = plus(common, "-Dkyu.registry.create=true", "-Dkyu.server.journal=" + journal);
        Proc s1 = Proc.start("server-1", dir, plus(srv, "-Dkyu.sim.disk.ms=4000"), SERVER);
        s1.awaitOutput("server ready", 15_000);
        Proc lec = Proc.start("lecturer", dir, plus(common, "-Dkyu.client.timeout.ms=8000",
                "-Dkyu.client.retries=4", "-Dkyu.client.backoff.ms=1000"), LECTURER, "submit KYU001 SPC2401 78");
        Thread.sleep(2_500);                    // request is inside the 4 s 'disk wait'
        s1.kill();
        Thread.sleep(500);
        Proc s2 = Proc.start("server-2", dir, srv, SERVER);
        lec.awaitExit(60_000);
        Proc check = Proc.start("lecturer-check", dir, common, LECTURER, "list SPC2401");
        check.awaitExit(30_000);
        long journaled = Files.readAllLines(journal).stream().filter(l -> l.startsWith("M|")).count();
        section("A1. Server killed mid-call, before the mark was stored",
                "- lecturer log:\n" + indent(lines(lec.output(), "FAILURE", "succeeded", "OK stored", "GAVE UP"))
                        + "- server-2 log:\n" + indent(lines(s2.output(), "applied", "duplicate", "recovered"))
                        + "- " + grep(check.output(), "LIST SPC2401") + "\n"
                        + "- journal entries for the mark: " + journaled + "\n"
                        + "- Result: the first attempt died with the server; the retry with the same request ID"
                        + " was applied by the new server exactly once.");
        s2.close();
        check.close();
    }

    // ----------------------------------------------------------------- A2

    /** Server killed AFTER storing the mark but before replying (the reply is lost). */
    static void serverKilledAfterApply() throws Exception {
        Path dir = ROOT.resolve("A2-server-killed-after-apply");
        int port = freePort();
        Path journal = dir.resolve("marks.journal");
        List<String> common = common(port, dir);
        List<String> srv = plus(common, "-Dkyu.registry.create=true", "-Dkyu.server.journal=" + journal);
        Proc s1 = Proc.start("server-1", dir, plus(srv, "-Dkyu.sim.postapply.ms=4000"), SERVER);
        s1.awaitOutput("server ready", 15_000);
        Proc lec = Proc.start("lecturer", dir, plus(common, "-Dkyu.client.timeout.ms=8000",
                "-Dkyu.client.retries=4", "-Dkyu.client.backoff.ms=1000"), LECTURER, "submit KYU001 SPC2401 78");
        s1.awaitOutput("applied req=", 15_000);   // stored and journaled; reply not yet sent
        Thread.sleep(300);
        s1.kill();
        Thread.sleep(500);
        Proc s2 = Proc.start("server-2", dir, srv, SERVER);
        lec.awaitExit(60_000);
        Proc check = Proc.start("lecturer-check", dir, common, LECTURER, "list SPC2401");
        check.awaitExit(30_000);
        long journaled = Files.readAllLines(journal).stream().filter(l -> l.startsWith("M|")).count();
        section("A2. Server killed after storing the mark, before replying",
                "- server-1 log:\n" + indent(lines(s1.output(), "applied"))
                        + "- lecturer log:\n" + indent(lines(lec.output(), "FAILURE", "succeeded", "OK stored", "GAVE UP"))
                        + "- server-2 log:\n" + indent(lines(s2.output(), "recovered", "duplicate", "applied"))
                        + "- " + grep(check.output(), "LIST SPC2401") + "\n"
                        + "- journal entries for the mark: " + journaled + " (must be 1)\n"
                        + "- Result: the client saw a failure and retried; server-2 recovered the request ID from the"
                        + " journal and ignored the duplicate. At-most-once held across a crash.");
        s2.close();
        check.close();
    }

    // ------------------------------------------------------------------ B

    /** A subscribed student's process is killed before publication. */
    static void subscriberOffline() throws Exception {
        Path dir = ROOT.resolve("B-subscriber-offline");
        int port = freePort();
        List<String> common = common(port, dir);
        try (Proc server = Proc.start("server", dir, plus(common, "-Dkyu.registry.create=true",
                "-Dkyu.server.journal=none"), SERVER);
             Proc a = startStudent(dir, common, "KYU001", server);
             Proc b = startStudent(dir, common, "KYU002", server);
             Proc c = startStudent(dir, common, "KYU003", server)) {
            run(dir, common, "lecturer-1", "submit KYU001 SPC2401 70; submit KYU002 SPC2401 61; submit KYU003 SPC2401 55");
            b.kill();                                   // laptop closed: no unsubscribe was sent
            long t0 = System.nanoTime();
            run(dir, common, "lecturer-2", "publish SPC2401");
            server.awaitOutput("publish SPC2401 finished", 30_000);
            long ms = (System.nanoTime() - t0) / 1_000_000;
            a.awaitOutput("MARK KYU001", 10_000);
            c.awaitOutput("MARK KYU003", 10_000);
            run(dir, common, "lecturer-3", "submit KYU001 SPC2401 72; publish SPC2401");
            server.awaitOutput("delivered 2/2", 15_000);
            section("B. A subscribed student goes offline before publishMarks",
                    "- server log:\n" + indent(lines(server.output(), "notifying", "FAILURE", "finished"))
                            + "- KYU001: " + grep(a.output(), "MARK KYU001") + "\n"
                            + "- KYU003: " + grep(c.output(), "MARK KYU003") + "\n"
                            + "- publish to all callbacks finished in " + ms + " ms (incl. lecturer JVM start)\n"
                            + "- Result: the dead listener failed (connection refused after ~2 s of Windows connect retries), was logged and removed, and did not"
                            + " stop the other two. The second publish targeted only the 2 live students.");
        }
    }

    // ------------------------------------------------------------------ C

    /** Added network delay: first slow but within the timeout, then longer than the timeout. */
    static void networkDelay() throws Exception {
        Path dir = ROOT.resolve("C-network-delay");
        int port = freePort();
        List<String> common = common(port, dir);
        try (Proc server = Proc.start("server", dir, plus(common, "-Dkyu.registry.create=true",
                "-Dkyu.server.journal=none"), SERVER)) {
            server.awaitOutput("server ready", 15_000);
            long base = timed(dir, common, "lecturer-0ms", "submit KYU001 SPC2401 60");
            long slow = timed(dir, plus(common, "-Dkyu.net.delay.ms=300"), "lecturer-300ms",
                    "submit KYU002 SPC2401 61");
            long over = timed(dir, plus(common, "-Dkyu.net.delay.ms=1500", "-Dkyu.client.timeout.ms=2500",
                    "-Dkyu.client.retries=2", "-Dkyu.client.backoff.ms=200"), "lecturer-1500ms",
                    "submit KYU003 SPC2401 62");
            Thread.sleep(6_000);                   // let orphaned attempts reach the server
            Proc check = run(dir, common, "lecturer-check", "list SPC2401");
            String overOut = Files.readString(dir.resolve("lecturer-1500ms.out"));
            section("C. Added network delay (applied to every message the lecturer JVM sends)",
                    "- no delay: lecturer process finished in " + base + " ms\n"
                            + "- 300 ms per message, 5 s timeout (default): finished in " + slow + " ms, "
                            + grep(Files.readString(dir.resolve("lecturer-300ms.out")), "OK stored") + "\n"
                            + "- 1500 ms per message, 2.5 s timeout: finished in " + over + " ms\n"
                            + indent(lines(overOut, "FAILURE", "succeeded", "OK stored", "GAVE UP"))
                            + "- server log for KYU003:\n" + indent(lines(server.output(), "KYU003"))
                            + "- " + grep(check.output(), "LIST SPC2401") + "\n"
                            + "- Result: delays inside the timeout only slow the call; delays beyond it cause"
                            + " timeouts and retries, and the server applies the mark once and ignores the late"
                            + " duplicates.");
        }
    }

    // ------------------------------------------------------------- helpers

    private static Proc startStudent(Path dir, List<String> common, String id, Proc server) throws Exception {
        server.awaitOutput("server ready", 15_000);
        Proc p = Proc.start("student-" + id, dir, common, STUDENT, id, "--no-console");
        p.awaitOutput("SUBSCRIBED", 15_000);
        return p;
    }

    private static Proc run(Path dir, List<String> props, String name, String cmds) throws Exception {
        Proc p = Proc.start(name, dir, props, LECTURER, cmds);
        p.awaitExit(60_000);
        return p;
    }

    private static long timed(Path dir, List<String> props, String name, String cmds) throws Exception {
        long t0 = System.nanoTime();
        run(dir, props, name, cmds);
        return (System.nanoTime() - t0) / 1_000_000;
    }

    private static List<String> common(int port, Path dir) {
        return List.of("-Dkyu.registry.host=localhost", "-Dkyu.registry.port=" + port,
                "-Dkyu.log.dir=" + dir.resolve("logs"), "-Dkyu.client.backoff.ms=300");
    }

    private static List<String> plus(List<String> base, String... more) {
        List<String> l = new ArrayList<>(base);
        l.addAll(List.of(more));
        return l;
    }

    private static int freePort() throws IOException {
        try (ServerSocket s = new ServerSocket(0)) {
            return s.getLocalPort();
        }
    }

    private static void section(String title, String body) {
        SUMMARY.append("\n## ").append(title).append("\n\n").append(body).append("\n");
        System.out.println("== " + title + " done");
    }

    private static long count(String text, String needle) {
        return text.lines().filter(l -> l.contains(needle)).count();
    }

    private static String grep(String text, String needle) {
        return text.lines().filter(l -> l.contains(needle)).map(FailureExperiments::strip)
                .findFirst().orElse("(no '" + needle + "' line)");
    }

    private static String lines(String text, String... needles) {
        return text.lines().filter(l -> Stream.of(needles).anyMatch(l::contains))
                .map(FailureExperiments::strip).collect(Collectors.joining("\n"));
    }

    /** Drops the thread name to keep summary lines short. */
    private static String strip(String l) {
        return l.replaceFirst(" \\[[^\\]]*(Connection|main|worker|notifier|rmi-call|housekeeping)[^\\]]*\\]", "");
    }

    private static String indent(String s) {
        return s.isBlank() ? "    (none)\n" : s.lines().map(l -> "    " + l).collect(Collectors.joining("\n")) + "\n";
    }

    private static void deleteTree(Path p) throws IOException {
        if (Files.exists(p)) {
            try (Stream<Path> w = Files.walk(p)) {
                w.sorted(Comparator.reverseOrder()).forEach(f -> f.toFile().delete());
            }
        }
    }
}
